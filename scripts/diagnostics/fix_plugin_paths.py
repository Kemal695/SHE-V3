"""Repair .flutter-plugins-dependencies paths left over from another machine.

`mobile/.flutter-plugins-dependencies` is generated by `flutter pub get`, which cannot run
on this host (Dart cannot spawn piped children - see README.md in this folder). The copy in
the tree came from another machine, so Gradle fails with:

    Plugin directory does not exist:
      C:\\Users\\kemal\\AppData\\Local\\Pub\\Cache\\hosted\\pub.dev\\firebase_core-3.15.2\\android

Two separate problems, both fixed here by TEXT substitution (not JSON re-encoding, which
would normalise the escaping):

  1. The user segment is `kemal`, not `hp`.
  2. Separators are stored DOUBLY escaped (`C:\\\\Users\\\\...`), which pathlib/os.path
     cannot resolve. Flutter's own loader tolerates this, but we normalise it so the paths
     are valid for anything that reads the file.

Run from `mobile/` after any checkout move.
"""
import pathlib
import re
import sys

P = pathlib.Path(".flutter-plugins-dependencies")
if not P.exists():
    sys.exit("run this from the mobile/ directory")

raw = P.read_text(encoding="utf-8")
orig = raw

home = pathlib.Path.home()
old_root = r"C:\\\\Users\\\\kemal\\\\AppData\\\\Local\\\\Pub\\\\Cache\\\\hosted\\\\pub.dev\\\\"
new_root = (
    str(home).replace("\\", "\\\\")
    + r"\\\\AppData\\\\Local\\\\Pub\\\\Cache\\\\hosted\\\\pub.dev\\\\"
)

n = raw.count(old_root)
raw = raw.replace(old_root, new_root)
print(f"rewrote {n} pub-cache root(s)")

# The custom BLE plugin is referenced by an old absolute path too.
old_plugin = r"D:\\\\she-v3\\\\mobile\\\\plugins\\\\flutter_esp_ble_prov\\\\"
new_plugin = str(pathlib.Path.cwd() / "plugins" / "flutter_esp_ble_prov").replace("\\", "\\\\") + "\\\\"
n2 = raw.count(old_plugin)
raw = raw.replace(old_plugin, new_plugin)
print(f"rewrote {n2} local plugin path(s)")

if raw != orig:
    P.write_text(raw, encoding="utf-8")
    print("file updated")
else:
    print("no change needed")

# Verify using the SAME decoding Flutter's json.loads would apply.
import json  # noqa: E402

d = json.loads(P.read_text(encoding="utf-8"))
seen, ok, miss = set(), 0, []
for _plat, items in d.get("plugins", {}).items():
    for it in items:
        p = it.get("path", "")
        if not p or p in seen:
            continue
        seen.add(p)
        # After json.loads a doubly-escaped path still contains double separators,
        # so normalise before stat().
        probe = re.sub(r"\\+", "\\\\", p).rstrip("\\/")
        if pathlib.Path(probe).is_dir():
            ok += 1
        else:
            miss.append(f"{it['name']} -> {p}")

print(f"distinct paths: {len(seen)} | exist: {ok} | missing: {len(miss)}")
for m in miss:
    print("  still missing:", m)
sys.exit(1 if miss else 0)
